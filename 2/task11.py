# todo: Дан номер месяца (1 — январь, 2 — февраль, ...). Вывести название соответствующего
# времени года ("зима", "весна" и т.д.).

month = int(input("Введите номер месяца: "))

match month:
  case 1 | 2 | 12:
    print("зима")
  case 3 | 4 | 5:
    print("весна")
  case 6 | 7 | 8:
    print("лето")
  case 9 | 10 | 11:
    print("осень")
  case _:
    print("Такого месяца не существует")