#todo: Даны три точки A , B , C на числовой оси. Найти длины отрезков AC и BC и их сумму.
# Примечание: все точки получаем через функцию input().

a = int(input("Введите координату A: "))
b = int(input("Введите координату B: "))
c = int(input("Введите координату C: "))

ac = abs(c - a)
bc = abs(b - c)

print("Длина отрезка AC: " + str(ac))
print("Длина отрезка BC: " + str(bc))
print("Сумма длин отрезков: ", str(ac + bc))